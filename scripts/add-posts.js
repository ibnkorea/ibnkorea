async function addPosts() {
  console.log('📝 예시 게시글 등록 시작...\n');

  if (!AIRTABLE_TOKEN || !AIRTABLE_BASE_ID) {
    console.error('❌ AIRTABLE_TOKEN 또는 AIRTABLE_BASE_ID 환경변수가 설정되지 않았습니다.');
    console.log('사용법: AIRTABLE_TOKEN=xxx AIRTABLE_BASE_ID=xxx node add-posts.js');
    process.exit(1);
  }

  let success = 0;
  let failed = 0;

  for (const post of posts) {
    try {
      const response = await fetch(
        `https://api.airtable.com/v0/${AIRTABLE_BASE_ID}/board2`,
        {
          method: 'POST',
          headers: {
            'Authorization': `Bearer ${AIRTABLE_TOKEN}`,
            'Content-Type': 'application/json'
          },
          body: JSON.stringify({
            fields: {
              title: post.title,
              content: post.content,
              summary: post.summary,
              category: post.category,
              thumbnailUrl: post.thumbnailUrl,
              tags: post.tags,
              date: post.date,
              views: 0,
              isPublic: true
            }
          })
        }
      );

      if (response.ok) {
        const result = await response.json();
        console.log(`✅ ${post.title}`);
        console.log(`   ID: ${result.id}\n`);
        success++;
      } else {
        const error = await response.text();
        console.log(`❌ ${post.title}`);
        console.log(`   오류: ${error}\n`);
        failed++;
      }
    } catch (error) {
      console.log(`❌ ${post.title}`);
      console.log(`   오류: ${error.message}\n`);
      failed++;
    }
  }

  console.log('\n📊 결과 요약');
  console.log(`   성공: ${success}개`);
  console.log(`   실패: ${failed}개`);
}

